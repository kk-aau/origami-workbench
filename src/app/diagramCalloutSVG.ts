import type {Doc} from '../core/types';
import type {CreaseDisplay} from './creaseDisplay';
import {creasePatternSVG,DISPLAY_PIXEL_MM,type CreasePatternStrokeOptions} from './creasePatternSVG';
import {diagramCalloutConnectors,diagramCalloutLocator,diagramCalloutTargets,validateDiagramCallouts,type DiagramCallout} from './diagramCallouts';

export type DiagramCalloutPaperMarkup=string|((callout:DiagramCallout,sourceUnits:number)=>string);
export interface DiagramCalloutSVGOptions {
  /** Generated drawing world markup, explicitly excluding all callouts. */
  paperMarkup:DiagramCalloutPaperMarkup;
  /** Generated CP world markup for this step's validated boundary state. */
  cpMarkup:(stateId:string,sourceUnits?:number,hideExistingCreases?:boolean)=>string;
  /** Main drawing world units per output pixel; each inset resamples at its own scale. */
  units?:number;
  /** Distinct for simultaneously mounted canvases/thumbnails. */
  idPrefix?:string;
  stroke?:string;
  strokeWidth?:number;
}
const escapeXML=(value:string)=>value.replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&apos;'}[c]!));
const token=(value:string)=>Array.from(value,c=>c.codePointAt(0)!.toString(16)).join('-');

/** Only strip the root of SVG generated by the application. Callers never
 * load user SVG, remote resources, or rendered markup from project metadata. */
export function diagramCalloutSourceMarkup(svg:string):string {
  const match=/^\s*<svg\b[^>]*>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if(!match)throw new Error('局部放大图来源缺少有效的 SVG 根节点。');
  return match[1];
}
export const diagramCalloutSVGBody=diagramCalloutSourceMarkup;
export function diagramCalloutCPMarkup(doc:Doc,display:CreaseDisplay,strokeOptions?:CreasePatternStrokeOptions):string {
  return diagramCalloutSourceMarkup(creasePatternSVG(doc,display,undefined,undefined,strokeOptions));
}
/** Each copied source gets its own IDs, including nested masks, clips and use
 * references. Reusing the main drawing's IDs would sample the wrong cutaway. */
export function diagramCalloutNamespaceMarkup(markup:string,prefix:string):string {
  prefix=`diagram-callout-source-${token(prefix)}`;
  const ids=new Map<string,string>();
  markup.replace(/(\s)id=(['"])(.*?)\2/g,(_whole,_space:string,_quote:string,id:string)=>{ids.set(id,`${prefix}-${token(id)}`);return '';});
  return markup.replace(/(\s)id=(['"])(.*?)\2/g,(_whole,space:string,quote:string,id:string)=>`${space}id=${quote}${ids.get(id)}${quote}`)
    .replace(/url\(\s*(['"]?)#([^\s)'"#]+)\1\s*\)/g,(whole,_quote:string,id:string)=>ids.has(id)?`url(#${ids.get(id)})`:whole)
    .replace(/(\s)((?:xlink:)?href)=(['"])#(.*?)\3/g,(whole,space:string,key:string,quote:string,id:string)=>ids.has(id)?`${space}${key}=${quote}#${ids.get(id)}${quote}`:whole);
}

/** Circular clips and transforms are shared by editor, thumbnails and exports.
 * Sources never contain callouts, so multiple insets cannot recurse. */
export function diagramCalloutsSVG(callouts:readonly DiagramCallout[],options:DiagramCalloutSVGOptions):string {
  validateDiagramCallouts(callouts);
  if(!callouts.length)return '';
  const width=options.strokeWidth??.7;
  if(!Number.isFinite(width)||width<=0)throw new Error('局部放大图边框线宽无效。');
  const units=options.units??DISPLAY_PIXEL_MM;
  if(!Number.isFinite(units)||units<=0)throw new Error('局部放大图输出比例无效。');
  const stroke=escapeXML(options.stroke??'#333333'),prefix=`diagram-callout-${token(options.idPrefix??'drawing')}`;
  return callouts.map((callout,index)=>{
    const {source}=callout,locator=diagramCalloutLocator(callout),id=`${prefix}-${index}`,targets=diagramCalloutTargets(callout);
    const sourceMarkup=(scale:number,stateId?:string)=>{
      const sourceUnits=units/scale;
      return source.kind==='paper'?(typeof options.paperMarkup==='function'?options.paperMarkup(callout,sourceUnits):options.paperMarkup):options.cpMarkup(stateId!,sourceUnits,callout.hideExistingCreases);
    };
    const circle=(center:readonly number[],radius:number,extra='')=>`<circle cx="${center[0]}" cy="${center[1]}" r="${radius}" ${extra}/>`;
    const outline=`fill="none" stroke="${stroke}" stroke-width="${width}"`;
    const connectors=targets.flatMap(({circle:target})=>diagramCalloutConnectors(callout,target)).map(([a,b])=>`<path d="M ${a.join(' ')} L ${b.join(' ')}" ${outline}/>`).join('');
    if(!callout.comparison){
      const {target}=callout,clip=`${id}-clip`,scale=target.radius/source.radius,markup=sourceMarkup(scale,source.kind==='cp'?source.stateId:undefined),content=diagramCalloutNamespaceMarkup(markup,`${id}-source`);
      return `<g data-diagram-callout="${escapeXML(callout.id)}"><defs><clipPath id="${clip}" clipPathUnits="userSpaceOnUse">${circle(target.center,target.radius)}</clipPath></defs>${circle(locator.center,locator.radius,outline)}${connectors}${circle(target.center,target.radius,'fill="white" stroke="none"')}<g clip-path="url(#${clip})"><g transform="translate(${target.center.join(' ')}) scale(${target.radius/source.radius}) translate(${-source.center[0]} ${-source.center[1]})">${content}</g></g>${circle(target.center,target.radius,outline)}</g>`;
    }
    const insets=targets.map(({part,circle:target,stateId,label})=>{
      const clip=`${id}-${part}-clip`,scale=target.radius/source.radius,markup=sourceMarkup(scale,stateId);
      const content=diagramCalloutNamespaceMarkup(markup,`${id}-${part}-source`);
      const caption=label?`<text data-diagram-callout-label="${part}" x="${target.center[0]}" y="${target.center[1]+target.radius*1.3}" text-anchor="middle" font-family="Microsoft YaHei,sans-serif" font-size="${target.radius*.18}" fill="${stroke}">${label}</text>`:'';
      return `<g data-diagram-callout-target="${part}"><defs><clipPath id="${clip}" clipPathUnits="userSpaceOnUse">${circle(target.center,target.radius)}</clipPath></defs>${circle(target.center,target.radius,'fill="white" stroke="none"')}<g clip-path="url(#${clip})"><g transform="translate(${target.center.join(' ')}) scale(${scale}) translate(${-source.center[0]} ${-source.center[1]})">${content}</g></g>${circle(target.center,target.radius,outline)}${caption}</g>`;
    }).join('');
    return `<g data-diagram-callout="${escapeXML(callout.id)}">${circle(locator.center,locator.radius,outline)}${connectors}${insets}</g>`;
  }).join('');
}
