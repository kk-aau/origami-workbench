import {polygonArea} from '../core/geometry';
import type {Doc,FoldGraph,Point,FlatFoldResult} from '../core/types';
import type {TessGraph,TessResult} from './tessellation';
import {hasWovenInternalBoundary,readTessParams} from './tessellation';
import {inspectWovenCutTopology} from './wovenCutTopology';
import type {FlatSide} from './flatPresentation';
import type {ModelOverlapReply} from './modelOverlapTask';

export interface TessFlatInput {key:string;graph:FoldGraph;checked:boolean;startingFace?:number;faceupFace?:number;wovenCutFoldedVertices?:Point[]}
export interface TessFlatFrame {id:number;input:TessFlatInput;result:FlatFoldResult;surface?:{side:FlatSide;reply:ModelOverlapReply}}

/** Keep the generator's face topology; rebuilding intersections on every frame is unnecessary. */
export function tessFlatInput(result:TessResult,doc:Doc,key:string,checked:boolean):TessFlatInput {
  if(hasWovenInternalBoundary(result)){
    const params=readTessParams((doc.metadata?.tessellation as {parameters?:unknown}|undefined)?.parameters);
    if(!params)throw new Error('切口折痕缺少原构造参数。');
    const inspected=inspectWovenCutTopology(result,params);
    if(!inspected.ok)throw new Error(inspected.reason);
    const topology=inspected.topology,original=result.fold as TessGraph&{edges_foldAngle:(number|null)[]},points=topology.sourceCP;
    const minX=Math.min(...points.map(p=>p[0])),minY=Math.min(...points.map(p=>p[1]));
    const span=Math.max(Math.max(...points.map(p=>p[0]))-minX,Math.max(...points.map(p=>p[1]))-minY),scale=200/span;
    const transform=(p:Point):Point=>[(p[0]-minX)*scale,(p[1]-minY)*scale];
    if(!Number.isFinite(scale)||scale<=0||doc.segments.length!==original.edges_vertices.length)throw new Error('切口折痕坐标或边数已变化。');
    for(const [i,[a,b]] of original.edges_vertices.entries()){
      const segment=doc.segments[i],pa=transform(points[a]),pb=transform(points[b]);
      if(segment.assignment!==original.edges_assignment[i]||segment.angle!==original.edges_foldAngle[i]||Math.hypot(segment.a[0]-pa[0],segment.a[1]-pa[1])>2e-6||Math.hypot(segment.b[0]-pb[0],segment.b[1]-pb[1])>2e-6)throw new Error('切口原折后形与当前折痕已不匹配，请重新构造。');
    }
    return {key,checked:true,graph:{...topology.splitGraph,vertices_coords:topology.splitGraph.vertices_coords.map(transform)},wovenCutFoldedVertices:topology.splitFolded.map(transform),startingFace:result.source.stationaryFoldFace as number};
  }
  const fold=result.fold as TessGraph;
  if(!fold.faces_vertices?.length||fold.edges_vertices.length!==doc.segments.length)throw new Error('当前镶嵌没有完整的纸面拓扑。');
  const coords:Point[]=Array(fold.vertices_coords.length);
  fold.edges_vertices.forEach(([a,b],i)=>{coords[a]=doc.segments[i].a;coords[b]=doc.segments[i].b;});
  if(coords.filter(Boolean).length!==coords.length||coords.some(p=>!p.every(Number.isFinite)))throw new Error('镶嵌纸面坐标不完整。');
  const faces=fold.faces_vertices.map(f=>polygonArea(f.map(v=>coords[v]))<0?[...f].reverse():[...f]);
  let graph:FoldGraph={vertices_coords:coords,edges_vertices:fold.edges_vertices,edges_assignment:doc.segments.map(s=>s.assignment),edges_foldAngle:doc.segments.map(s=>s.angle),faces_vertices:faces};
  // Backend serialization sorts current coordinates; vertices can exchange IDs
  // during scaling even though the physical topology is unchanged. Anchor IDs
  // to the angle/scale-independent construction coefficients instead.
  if(result.preview?.kind==='shrink-rotate'&&result.preview.vertices.length===coords.length){
    const labels=result.preview.vertices.map(p=>p.map(v=>(Math.round(v*1e8)/1e8).toFixed(8)).join(','));
    if(new Set(labels).size===labels.length){
      const ids=coords.map((_,i)=>i).sort((a,b)=>labels[a]<labels[b]?-1:labels[a]>labels[b]?1:0),remap:number[]=[];ids.forEach((v,i)=>remap[v]=i);
      const edges=graph.edges_vertices.map(([a,b],i)=>({edge:[remap[a],remap[b]].sort((a,b)=>a-b) as [number,number],assignment:graph.edges_assignment[i],angle:graph.edges_foldAngle[i]})).sort((a,b)=>a.edge[0]-b.edge[0]||a.edge[1]-b.edge[1]);
      const sortedFaces=faces.map(face=>{const f=face.map(v=>remap[v]),start=f.indexOf(Math.min(...f));return [...f.slice(start),...f.slice(0,start)];}).sort((a,b)=>{for(let i=0;i<Math.min(a.length,b.length);i++)if(a[i]!==b[i])return a[i]-b[i];return a.length-b.length;});
      graph={vertices_coords:ids.map(v=>coords[v]),edges_vertices:edges.map(e=>e.edge),edges_assignment:edges.map(e=>e.assignment),edges_foldAngle:edges.map(e=>e.angle),faces_vertices:sortedFaces};
    }
  }
  // A circular twist's selected face is numbered in the original notebook's
  // one-based face order.  Only the true face-reflected form is generated by
  // the solver; circularizedFoldedForm is an illustration, never input here.
  const family=(result.stats as {parameters?:{family?:string}}).parameters?.family;
  let startingFace:number|undefined;
  if(result.source.paperMethod==='inscribed-pattern-clip-v1'){
    // Clipping can remove the original anchor or renumber its face. The
    // crop supplies its own anchor in the current crease-face order.
    const face=result.source.paperStartingFace;
    if(typeof face!=='number'||!Number.isInteger(face)||face<0||face>=faces.length)
      throw new Error('内切纸张固定折痕面编号无效。');
    startingFace=face;
  }else if(family==='circular-twist'){
    const face=result.source.foldedFormStationaryFace;
    if(typeof face!=='number'||!Number.isInteger(face)||face<1||face>faces.length)throw new Error('圆形扭转固定面编号无效。');
    startingFace=face-1;
  }else if(family==='woven-lines'||family==='woven'){
    // The saved mother-face index identifies the inset cell, while the flat
    // solver needs its corresponding face in the generated crease pattern.
    const face=result.source.stationaryFoldFace;
    if(typeof face!=='number'||!Number.isInteger(face)||face<0||face>=faces.length)throw new Error('编织固定折痕面编号无效。');
    startingFace=face;
  }else if(family==='custom'&&result.source.output==='tile-twists'){
    // The source graph's saved face number is zero-based here.  It is a
    // geometric anchor, not a layer-order claim.
    const face=result.source.foldedFormStationaryFace;
    if(typeof face!=='number'||!Number.isInteger(face)||face<0||face>=faces.length)
      throw new Error('逐块扭转固定折痕面编号无效。');
    startingFace=face;
  }
  return {key,checked,graph,...(startingFace===undefined?{}:{startingFace})};
}

/** Anchor near the paper centre, with a geometric tie-break independent of vertex IDs. */
export function tessFlatRoot(graph:FoldGraph):number {
  const xs=graph.vertices_coords.map(p=>p[0]),ys=graph.vertices_coords.map(p=>p[1]);
  const x=(Math.min(...xs)+Math.max(...xs))/2,y=(Math.min(...ys)+Math.max(...ys))/2;
  const faces=(graph.faces_vertices??[]).map((f,index)=>{
    const cx=f.reduce((s,v)=>s+graph.vertices_coords[v][0],0)/f.length,cy=f.reduce((s,v)=>s+graph.vertices_coords[v][1],0)/f.length;
    return {index,d:Math.round(((cx-x)**2+(cy-y)**2)*1e7)/1e7,x:cx,y:cy};
  });
  faces.sort((a,b)=>a.d-b.d||a.x-b.x||a.y-b.y);return faces[0]?.index??0;
}

/** Preserve the old root for live edits, except when the user chose one explicitly. */
export function tessFlatStartingFace(input:TessFlatInput,previous:FlatFoldResult|null):number{
  if(input.startingFace!==undefined)return input.startingFace;
  const graph=previous?.geometry.graph;
  if(graph&&['faces_vertices','edges_vertices','edges_assignment'].every(key=>JSON.stringify(graph[key])===JSON.stringify(input.graph[key]))
    &&Number.isInteger(previous?.geometry.startingFace))return previous!.geometry.startingFace!;
  return tessFlatRoot(input.graph);
}
