import {test} from 'node:test';
import assert from 'node:assert/strict';
import {blankDoc} from '../../src/app/state';
import {splitEditableSegments} from '../../src/app/planarize';
import {setStartingFace,resolveStartingFace} from '../../src/app/flatFoldSettings';
import {buildFold} from '../../src/core/geometry';
import {computeFlatFold} from '../../src/core/flatFold';
import {exportModelSnapshot} from '../../src/core/modelSnapshot';
import {prepareModelSnapshot} from '../../src/app/modelSnapshot';
import {emptyFoldedModelCollection,foldedModelCollectionReducer} from '../../src/app/foldedModelCollection';
import {exportModelCollection,prepareModelCollection} from '../../src/app/modelCollectionFile';
import {exportArtworkProject,prepareArtworkProject} from '../../src/app/artworkProject';
import {tessPreset} from '../../src/app/tessellation';

for(const stale of [false,true])test(`default-root results roundtrip with ${stale?'stale':'valid'} legacy manual roots`,()=>{
  const raw=blankDoc('默认起始面兼容',100,100);
  raw.segments.push({id:'fold',a:[50,0],b:[50,100],assignment:'M',angle:-180});
  const source=setStartingFace(splitEditableSegments(raw),1);
  if(stale)source.flatFold!.startingFace=source.flatFold!.startingFace.map(([x,y])=>[x+1,y]);
  const before=structuredClone(source),graph=buildFold(source).graph;
  assert.deepEqual(resolveStartingFace(source,graph),{face:stale?0:1,stale});
  const result=computeFlatFold(source);
  assert.equal(result.geometry.status,'ready');assert.equal(result.layers.status,'solved');
  assert.equal(result.geometry.startingFace,0);
  const standalone=prepareModelSnapshot(exportModelSnapshot(source,result));
  assert.equal(standalone.result.geometry.startingFace,0);
  assert.deepEqual(standalone.result.geometry.vertices,result.geometry.vertices);
  assert.deepEqual(resolveStartingFace(standalone.doc,standalone.graph),{face:0,stale:false});
  const models=foldedModelCollectionReducer(emptyFoldedModelCollection(),{type:'add',id:'default-result',name:'默认平折',source:{doc:source,graph},result});
  const collection=prepareModelCollection(exportModelCollection(source,models));
  assert.deepEqual(collection.doc,source);
  assert.deepEqual(collection.collection.entries[0].source.doc,source,'restoring a collection must not rewrite the model source and make it stale');
  const text=exportArtworkProject({editor:source,models,diagram:null,simulation:null,construction:{tessellation:tessPreset('twist'),curve:null}}),loaded=prepareArtworkProject(text);
  assert.deepEqual(loaded.editor,source);
  assert.deepEqual(loaded.models.entries[0].source.doc,loaded.editor,'a current result stays current after restoring the complete artwork');
  assert.equal(loaded.models.entries[0].history.present!.geometry.startingFace,0);
  assert.deepEqual(loaded.models.entries[0].history.present!.geometry.vertices,result.geometry.vertices);
  assert.deepEqual(JSON.parse(exportArtworkProject(loaded)),JSON.parse(text));
  assert.deepEqual(source,before,'computing or saving does not alter the editor');
});
