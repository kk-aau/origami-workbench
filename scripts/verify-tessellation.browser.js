async page => {
  const results=[],check=(ok,message)=>{if(!ok)throw Error(message);results.push(message);};
  const button=name=>page.getByRole('button',{name,exact:true});
  const recovery=button('保留当前工程');if(await recovery.count())await recovery.click();
  const initialClose=button('关闭窗口');if(await initialClose.count())await initialClose.click();
  const save=async()=>{await button('保存工程').click();await page.locator('.save-dot.saved').waitFor();};
  const snapshot=async()=>{await save();return page.evaluate(async()=>{const name=document.querySelector('[aria-label="工程名称"]').value;const {projects}=await(await fetch('/api/projects')).json();const p=projects.find(p=>p.name===name);return(await(await fetch('/api/projects/'+p.id)).json()).doc;});};
  const generate=async()=>{const received=page.waitForResponse(r=>r.url().endsWith('/api/tessellate'));await button('生成预览').click();const response=await received;check(response.ok(),'生成接口成功');await button('采用折痕副本 →').waitFor();await page.waitForFunction(()=>!document.querySelector('.context-toolbar .primary')?.disabled);return response.json();};
  await page.setViewportSize({width:1000,height:720});
  await save();await button('镶嵌设计').click();await button('01 单元扭转').click();
  const originalName=await page.getByLabel('工程名称',{exact:true}).inputValue();
  const twist=await generate();check(twist.stats.kind==='polygon_twist','独立扭转算法返回真实折痕');
  check(await page.getByLabel('工程名称',{exact:true}).inputValue()===originalName,'预览不改当前工程');
  check(await page.locator('[data-segment]').count()===twist.stats.edges,'画布显示全部扭转边');
  check(await page.locator('.inspector').evaluate(e=>e.scrollHeight<=e.clientHeight+1),'1000×720 参数面板不需要滚动');
  await button('反向扭转').click();check(await button('采用折痕副本 →').isDisabled(),'变更参数禁止采用旧候选');
  const reversed=await generate();check(reversed.stats.parameters.angle===-36,'反向扭转传递负角');
  await button('采用折痕副本 →').click();check(await button('折痕编辑').getAttribute('aria-pressed')==='true','采用后进入可编辑工程');
  const adopted=await snapshot();check(adopted.metadata.tessellation.parameters.family==='twist','保存扭转参数与来源');
  const stored=JSON.stringify(adopted.segments);
  await button('镶嵌设计').click();await button('02 周期拼接').click();
  await page.getByLabel('平铺类型',{exact:true}).selectOption('triangle');
  await page.getByLabel('行数',{exact:true}).fill('2');await page.getByLabel('行数',{exact:true}).press('Enter');
  const periodic=await generate();check(periodic.stats.tiles===12,'2×3 三角格生成十二个连续单元');
  await button('母结构').click();check(await page.locator('[data-segment]').count()===periodic.mother.edges_vertices.length,'母结构视图显示共享边');
  check(await page.locator('.inspector').evaluate(e=>e.scrollHeight<=e.clientHeight+1),'周期拼接参数与检查在小窗口完整显示');
  await page.screenshot({path:'output/playwright/tessellation-periodic-mother.png'});
  await button('折痕图').click();check(await page.locator('[data-segment]').count()===periodic.stats.edges,'折痕视图可切回');
  check(JSON.stringify((await snapshot()).segments)===stored,'再次生成不覆盖已采用副本');
  await button('采用折痕副本 →').click();const periodicDoc=await snapshot();
  check(periodicDoc.metadata.tessellation.parameters.rows===2,'周期参数保存到新工程');
  await button('导出作品').click();await page.getByRole('combobox',{name:'输出格式',exact:true}).selectOption('json');
  const download=page.waitForEvent('download');await button('导出文件').click();const file=await download;
  await file.saveAs('output/playwright/tessellation-roundtrip.zhezhi.json');
  const close=button('关闭窗口');if(await close.count())await close.click();
  await page.getByLabel('折痕工程文件',{exact:true}).setInputFiles('output/playwright/tessellation-roundtrip.zhezhi.json');
  const reopened=await snapshot();check(JSON.stringify(reopened.metadata)===JSON.stringify(periodicDoc.metadata),'下载工程再导入保留构造参数和检查信息');
  check(JSON.stringify(reopened.segments)===JSON.stringify(periodicDoc.segments),'下载工程再导入保留山谷和坐标');
  await button('镶嵌设计').click();await button('03 原始—对偶').click();
  const primal=await generate();check(primal.stats.parameters.family==='primal-dual','原始—对偶旧算法通过新入口生成');
  await button('02 周期拼接').click();await page.getByLabel('平铺类型',{exact:true}).selectOption('triangle');
  for(const [label,value] of [['旋转角度','60'],['缩放比例','0.5']]){await page.getByLabel(label,{exact:true}).fill(value);await page.getByLabel(label,{exact:true}).press('Enter');}
  const failed=page.waitForResponse(r=>r.url().endsWith('/api/tessellate'));await button('生成预览').click();await failed;
  await page.waitForFunction(()=>document.querySelector('.context-toolbar .outline')?.textContent==='生成预览');
  check(await button('采用折痕副本 →').isDisabled(),'几何相交结果禁止采用');
  await button('恢复默认').click();await generate();
  await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:'output/playwright/tessellation-complete.png'});
  return {passed:results.length,results};
}
