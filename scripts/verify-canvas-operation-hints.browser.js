async page=>{
  const checks=[],check=(ok,message)=>{if(!ok)throw Error(message);checks.push(message);};
  const viewport=page.viewportSize(),suffix=viewport.width+'x'+viewport.height;
  const settle=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const svg=page.locator('svg.crease-canvas').first();
  const cancel=async()=>{await page.keyboard.press('Escape');await settle();};
  const point=async([x,y])=>svg.evaluate((element,[x,y])=>{const p=new DOMPoint(x,y).matrixTransform(element.getScreenCTM());return[p.x,p.y];},[x,y]);
  const click=async p=>{await page.mouse.click(...await point(p));await settle();};
  const state=async()=>({box:await svg.boundingBox(),view:await svg.getAttribute('viewBox')});
  const stable=(before,after,message)=>{if(JSON.stringify(before)!==JSON.stringify(after))throw Error(message+' '+JSON.stringify({before,after}));checks.push(message);};
  const tool=async name=>{await cancel();await page.locator('button[data-tool="'+name+'"]').click();await settle();};
  const keep=page.getByRole('button',{name:'保留当前工程',exact:true});if(await keep.count())await keep.click();
  await svg.waitFor();
  const initial=await state();
  await tool('continuous');const before=await state();
  stable(initial,before,'切换到有参数的连续反射工具不改变画布边界和视口');
  await click([25,100]);await click([75,100]);
  check(await page.getByRole('button',{name:'确认连续反射',exact:true}).isVisible(),'连续反射候选的确认按钮仍可使用');
  stable(before,await state(),'连续反射参数、结果与确认按钮出现时画布保持原位');
  await tool('angledirection');const angleBefore=await state();
  await click([25,50]);await click([75,50]);
  check(await page.getByRole('combobox',{name:'方向候选',exact:true}).isVisible(),'角度方向候选仍可使用');
  stable(angleBefore,await state(),'方向候选新增一行时画布边界和视口不变');
  await page.locator('.canvas-parameter-panel').hover();await page.mouse.wheel(0,180);await settle();
  stable(angleBefore,await state(),'参数区域内滚动不会触发画布缩放');
  await page.screenshot({path:'output/playwright/canvas-jitter/angle-candidates-stable-'+suffix+'.png'});
  await page.mouse.move(...await point([100,120]));await page.mouse.wheel(0,180);await settle();
  check((await state()).view!==angleBefore.view,'在画布上滚轮仍能缩放');
  await tool('text');const textBefore=await state();await click([100,100]);
  check(await page.locator('.canvas-parameter-panel').innerText().then(text=>text.length>0),'文字编辑参数显示在可操作的悬浮区域');
  stable(textBefore,await state(),'文字编辑参数出现时画布不移动');await cancel();
  await page.getByRole('button',{name:'显示设置',exact:true}).click();
  await page.getByRole('checkbox',{name:'显示顶部操作说明',exact:true}).uncheck();
  await page.getByRole('checkbox',{name:'显示鼠标旁操作提示',exact:true}).uncheck();
  await page.getByRole('button',{name:'保存显示设置',exact:true}).click();
  await page.getByRole('button',{name:'关闭窗口',exact:true}).click();
  await tool('line');await page.mouse.move(...await point([100,100]));await settle();
  check(await page.locator('.canvas-tool-guide').count()===0,'关闭顶部操作说明后不再显示顶部工具说明');
  check(await page.locator('[data-cursor-tool-hint]').count()===0,'关闭鼠标旁操作提示后不再显示跟随提示');
  await page.screenshot({path:'output/playwright/canvas-jitter/hints-hidden-'+suffix+'.png'});
  await page.reload();await page.locator('.app-header').waitFor();
  const keepAfterReload=page.getByRole('button',{name:'保留当前工程',exact:true});if(await keepAfterReload.count())await keepAfterReload.click();
  if(!await svg.isVisible())await page.getByRole('button',{name:'＋ 新建空白',exact:true}).first().click();
  await svg.waitFor();
  await page.mouse.move(...await point([100,100]));await settle();
  check(await page.locator('.canvas-tool-guide').count()===0&&await page.locator('[data-cursor-tool-hint]').count()===0,'刷新后仍记住两个提示开关');
  await page.getByRole('button',{name:'显示设置',exact:true}).click();
  await page.getByRole('checkbox',{name:'显示鼠标旁操作提示',exact:true}).check();
  await page.getByRole('button',{name:'保存显示设置',exact:true}).click();
  await page.getByRole('button',{name:'关闭窗口',exact:true}).click();
  await page.mouse.move(...await point([100,100]));await settle();
  check(await page.locator('.canvas-tool-guide').count()===0&&await page.locator('[data-cursor-tool-hint]').count()===1,'两个开关可独立控制');
  return{passed:checks.length,checks};
}
